/**
 * Resolve the generator strings for a page locale.
 * `locale` is the URL directory used by the localized pages
 * ('' or 'en' for English, 'zh-cn', 'zh-tw', …).
 */
export function generatorStringsFor(locale: string): GeneratorStrings {
  const key = locale.toLowerCase().replace(/\/+$/, '');
  if (!key || key === 'en' || key === '/') return GENERATOR_I18N.en;
  return GENERATOR_I18N[key] ?? GENERATOR_I18N.en;
}
