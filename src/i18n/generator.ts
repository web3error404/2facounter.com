/**
 * Translations for every string inside the 2FA generator widget
 * (Generator.astro markup + dynamic strings in scripts/generator.ts).
 *
 * Why a dedicated dictionary: the widget's text used to be hardcoded
 * English, so the tool stayed English on every localized page. Each
 * locale page now passes its URL locale to <Generator />, which
 * renders the static labels server-side and ships the full string set
 * for that locale as a JSON data island that generator.ts reads.
 *
 * Tone follows each locale's homepage: Sie-form German, vous-form
 * French, informal Italian, Spanish/Portuguese/Brazillian informal,
 * polite Korean, Vietnamese/Japanese/Chinese per their pages.
 *
 * `{tail}`, `{desc}`, `{code}` are placeholders filled by the client
 * at display time (see fmt() in scripts/generator.ts) — they must be
 * kept verbatim in every translation.
 */

export interface GeneratorStrings {
  /* ── Static markup (Generator.astro) ─────────────────────── */
  /** aria-label of the whole widget section */
  ariaSection: string;
  /** aria-label of the left (key input) panel */
  ariaInput: string;
  /** Text label above the secret key textarea */
  labelSecret: string;
  /** Textarea placeholder */
  placeholder: string;
  /** "Paste Key" button label */
  pasteKey: string;
  /** aria-label of the Scan QR / Upload split button group */
  ariaSplit: string;
  /** tooltip of the camera-scan half */
  titleScan: string;
  /** "Scan QR" button label */
  scanQr: string;
  /** tooltip of the upload half */
  titleUpload: string;
  /** "Upload" button label */
  upload: string;
  /** aria-label of the right (token/timer) panel */
  ariaTimerPanel: string;
  /** "Timer" heading */
  labelTimer: string;
  /** "Copy Code" button label */
  copyCode: string;
  /** transient "Copied ✓" label */
  copied: string;
  /** "Recent keys" heading */
  recentHeading: string;
  /** "Clear all" button label */
  clearAll: string;
  /** armed (confirm) label of the two-step clear */
  reallyClear: string;
  /** tooltip/title of the clear button */
  titleClear: string;
  /** bold lead of the privacy note (incl. trailing punctuation) */
  privacyLead: string;
  /** rest of the privacy note */
  privacyBody: string;
  /** aria-label of the camera modal */
  ariaCam: string;
  /** camera modal header text */
  camTitle: string;
  /** close-camera button aria-label */
  camClose: string;
  /** camera modal footer note */
  camNote: string;
  /** seconds suffix appended to the countdown number, e.g. " s" / "秒" */
  seconds: string;

  /* ── Dynamic strings (scripts/generator.ts) ──────────────── */
  toastClipboardEmpty: string;
  toastClipboardBlocked: string;
  toastNoCode: string;
  toastInvalid: string;
  /** fallback account label when the key has no issuer/label */
  liveKey: string;
  /** masked name for bare keys — {tail} = last 4 secret chars */
  keyMask: string;
  /** title of the open-button on a recent-keys row */
  loadKeyTitle: string;
  /** aria-label of the delete button — {desc} = entry label */
  removeKeyAria: string;
  toastRecentsCleared: string;
  toastCopied: string;
  /** sr-only announcement when the code rotates — {code} = the code */
  announceNewCode: string;
  toastDecoding: string;
  toastDecoderFail: string;
  toastQrInvalidPayload: string;
  toastQrImported: string;
  toastNoQr: string;
  toastFileUnreadable: string;
  toastCamDenied: string;
  toastCamUnavailable: string;
  toastQrNotKey: string;
}

